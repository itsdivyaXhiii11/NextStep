const PDFDocument = require('pdfkit');

function generateLOR(lorData) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margins: { top: 72, bottom: 72, left: 72, right: 72 } });
    const chunks = [];

    doc.on('data', chunk => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const { student, faculty, institution_name, program_name, purpose, additional_info, approved_at } = lorData;
    const date = new Date(approved_at || new Date()).toLocaleDateString('en-IN', { day: 'numeric', month: 'long', year: 'numeric' });

    // Header
    doc.fontSize(14).font('Helvetica-Bold').text('GSSS Institute of Engineering & Technology for Women', { align: 'center' });
    doc.fontSize(11).font('Helvetica').text('Mysuru, Karnataka — 570009', { align: 'center' });
    doc.moveDown(0.5);
    doc.moveTo(72, doc.y).lineTo(523, doc.y).stroke();
    doc.moveDown(1);

    // Date and subject
    doc.fontSize(11).font('Helvetica').text(`Date: ${date}`, { align: 'right' });
    doc.moveDown(0.5);
    doc.font('Helvetica-Bold').text('LETTER OF RECOMMENDATION', { align: 'center', underline: true });
    doc.moveDown(1);

    // Salutation
    doc.font('Helvetica').fontSize(11).text('To,');
    doc.text('The Admissions Committee / Concerned Authority');
    if (institution_name) doc.text(institution_name);
    doc.moveDown(0.5);
    doc.text('Subject: Letter of Recommendation for ' + (student?.name || '') + (program_name ? ` for ${program_name}` : ''));
    doc.moveDown(1);

    doc.text('Dear Sir/Madam,');
    doc.moveDown(0.5);

    const body = `It is with great pleasure and confidence that I, ${faculty?.name || ''}, ${faculty?.designation || 'Faculty Member'}, Department of ${faculty?.department || 'Engineering'}, GSSS Institute of Engineering & Technology for Women, Mysuru, recommend ${student?.name || 'the student'}${student?.usn ? ` (USN: ${student.usn})` : ''} for ${purpose || 'higher studies / placement opportunities'}.

During my interaction with ${student?.name?.split(' ')[0] || 'the student'}, I have had the opportunity to observe their academic capabilities and personal qualities closely. They have consistently demonstrated sincerity, dedication, and an ability to grasp complex concepts with remarkable ease.${additional_info ? `\n\n${additional_info}` : ''}

I am confident that ${student?.name?.split(' ')[0] || 'they'} has the intellectual ability, work ethic, and personal qualities necessary to excel in their chosen field. I recommend them without reservation for ${program_name ? `the ${program_name} program at ${institution_name || 'your institution'}` : 'the opportunity they have applied for'}.

Please feel free to contact me if you require any further information.`;

    doc.text(body, { align: 'justify', lineGap: 4 });
    doc.moveDown(2);

    // Signature
    doc.text('Yours sincerely,');
    doc.moveDown(2);
    doc.font('Helvetica-Bold').text(faculty?.name || '');
    doc.font('Helvetica').text(faculty?.designation || 'Faculty');
    doc.text('Department of ' + (faculty?.department || 'Engineering'));
    doc.text('GSSS Institute of Engineering & Technology for Women');
    doc.text('Mysuru — 570009');

    // Footer
    doc.fontSize(9).fillColor('#888888')
      .text(`Generated by GSSS NextStep | Document ID: ${lorData.id?.slice(0, 8).toUpperCase() || 'N/A'} | ${date}`,
        72, 750, { align: 'center', width: 451 });

    doc.end();
  });
}

module.exports = { generateLOR };
